package variable;

public class Var2 {
    public static void main(String[] args) {
        // 1. 변수 선언과 초기화를 각각 따로
        int a;
        a = 10;
        System.out.println(a);

        // 2. 변수 선언과 초기화를 한 번에
        int b = 20;
        System.out.println(b);

        // 3. 여러 변수 선언과 초기화를 한 번에
        int c = 30, d = 40;
        System.out.println(c);
        System.out.println(d);
    }
}
